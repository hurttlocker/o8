#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  MOBILE_INBOX_DELTA_FEATURE_ID,
  requireRealtimeFeature,
} from './lib/realtime-protocol-features.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = join(root, 'protocol', 'realtime', 'contract.json');
const desktopOutput = join(root, 'src', 'lib', 'realtime', 'generated-contract.ts');
const portableMobileOutput = join(root, 'protocol', 'realtime', 'generated', 'mobile-realtime-contract.ts');
const portableContractSnapshot = join(root, 'protocol', 'realtime', 'generated', 'contract.json');
const mobileRootFlag = process.argv.indexOf('--mobile-root');
const mobileRoot = mobileRootFlag >= 0 ? resolve(process.argv[mobileRootFlag + 1] ?? '') : null;
const mobileOutput = mobileRoot
  ? join(mobileRoot, 'src', 'o8', 'generated', 'realtime-contract.ts')
  : null;
const mobileContractSnapshot = mobileRoot
  ? join(mobileRoot, 'src', 'o8', 'generated', 'realtime-contract.json')
  : null;
const check = process.argv.includes('--check');

const raw = readFileSync(contractPath, 'utf8');
const contract = JSON.parse(raw);
const digest = createHash('sha256').update(raw).digest('hex');
const quoted = (values) => values.map((value) => `'${value}'`).join(' | ');
const quotedStream = (value) => value.includes('${string}') ? `\`${value}\`` : `'${value}'`;
const featureIds = contract.optionalFeatures.map((feature) => feature.id);
if (new Set(featureIds).size !== featureIds.length) {
  throw new Error('Realtime optional feature ids must be unique.');
}
const mobileInboxDeltaFeature = requireRealtimeFeature(
  contract.optionalFeatures,
  MOBILE_INBOX_DELTA_FEATURE_ID,
  'mobile.inbox.delta',
).id;
const featureRows = contract.optionalFeatures.map((feature) => (
  `  '${feature.id}': { introducedIn: ${feature.introducedIn}, removalDate: ${feature.removalDate ? `'${feature.removalDate}'` : 'null'} },`
)).join('\n');
const legacy = contract.compatibility.legacySubscribeWithoutHello;
const renderField = (field) => {
  const comment = field.comment ? `  /** ${field.comment} */\n` : '';
  return `${comment}  ${field.name}${field.optional ? '?' : ''}: ${field.type};`;
};
const renderDeclaration = (declaration) => {
  if (declaration.kind === 'union') {
    return `export type ${declaration.name} =\n${declaration.members.map((member) => `  | ${member}`).join('\n')};`;
  }
  if (declaration.kind !== 'interface') {
    throw new Error(`Unsupported realtime type declaration kind: ${declaration.kind}`);
  }
  const parameters = declaration.typeParameters?.length
    ? `<\n${declaration.typeParameters.map((parameter) => `  ${parameter},`).join('\n')}\n>`
    : '';
  const inheritance = declaration.extends?.length
    ? ` extends ${declaration.extends.join(', ')}`
    : '';
  return `export interface ${declaration.name}${parameters}${inheritance} {\n${declaration.fields.map(renderField).join('\n')}\n}`;
};
const typeDeclarations = contract.typeDeclarations.map(renderDeclaration).join('\n\n');
const declarationNames = new Set(contract.typeDeclarations.map((declaration) => declaration.name));
for (const metadata of [...Object.values(contract.sharedShapes), ...Object.values(contract.messages)]) {
  if (!declarationNames.has(metadata.typeDeclaration)) {
    throw new Error(`Unknown realtime type declaration reference: ${metadata.typeDeclaration}`);
  }
}
const artifactDigestPlaceholder = '0'.repeat(64);

const outputTemplate = `// Generated by scripts/generate-realtime-protocol.mjs from protocol/realtime/contract.json.
// Contract SHA-256: ${digest}. Do not edit this file by hand.
// Artifact SHA-256: ${artifactDigestPlaceholder}.

export const REALTIME_CONTRACT_SHA256 = '${digest}' as const;
export const REALTIME_GENERATED_ARTIFACT_SHA256 = '${artifactDigestPlaceholder}' as const;
export const REALTIME_PROTOCOL_VERSION = ${contract.protocol.current} as const;
export const REALTIME_MINIMUM_PROTOCOL_VERSION = ${contract.protocol.minimumSupported} as const;
export const MOBILE_INBOX_DELTA_CAPABILITY = '${mobileInboxDeltaFeature}' as const;
export const REALTIME_OPTIONAL_FEATURES = [${featureIds.map((id) => `'${id}'`).join(', ')}] as const;
export type RealtimeOptionalFeature = typeof REALTIME_OPTIONAL_FEATURES[number];
export type RealtimeProtocolVersion = ${contract.protocol.versions.map((item) => item.version).join(' | ')};
export type RealtimeClientKind = ${quoted(contract.clientKinds)};
export type RealtimeStreamKey = ${contract.streams.map(quotedStream).join(' | ')};
export type RealtimeDeliveryMode = ${quoted(contract.deliveryModes)};
export type RealtimeHealthState = ${quoted(contract.healthStates)};

export const REALTIME_FEATURE_METADATA: Readonly<Record<RealtimeOptionalFeature, {
  introducedIn: RealtimeProtocolVersion;
  removalDate: string | null;
}>> = {
${featureRows}
};

export const REALTIME_LEGACY_SUBSCRIPTION = {
  supported: ${legacy.supported},
  protocol: ${legacy.protocol},
  removalDate: '${legacy.removalDate}',
  removalProtocol: ${legacy.removalProtocol},
} as const;

${typeDeclarations}
`;
const artifactDigest = createHash('sha256').update(outputTemplate).digest('hex');
const output = outputTemplate.replaceAll(artifactDigestPlaceholder, artifactDigest);

function writeOrCheck(path, content) {
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`Realtime protocol output drifted: ${path}`);
      process.exitCode = 1;
    }
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

writeOrCheck(desktopOutput, output);
writeOrCheck(portableMobileOutput, output);
writeOrCheck(portableContractSnapshot, raw);
if (mobileOutput) writeOrCheck(mobileOutput, output);
if (mobileContractSnapshot) writeOrCheck(mobileContractSnapshot, raw);
