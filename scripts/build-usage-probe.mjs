import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({ entryPoints: [join(root, 'src/lib/usage/remote-probe.ts')], bundle: true,
  platform: 'node', target: 'node22', format: 'iife', globalName: 'o8UsageProbe', minify: true, write: false,
  alias: { '@': join(root, 'src'), 'server-only': join(root, 'scripts/server-only-stub.js') }, legalComments: 'inline' });
const source = '// Generated by scripts/build-usage-probe.mjs. Shared read-only usage collectors, no host dependency.\n'
  + `export const REMOTE_USAGE_PROBE = ${JSON.stringify(result.outputFiles[0].text)};\n`;
const target = join(root, 'src/lib/usage/remote-probe.generated.ts');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error('Usage probe is stale. Run node scripts/build-usage-probe.mjs.');
} else await writeFile(target, source);
