export function adHocLaneTitle(kind?: 'chat' | 'llm-chat' | 'terminal' | 'canvas' | 'orchestrator' | 'fleet-canvas') {
  if (kind === 'terminal') return 'Terminal';
  if (kind === 'canvas') return 'Inspector';
  if (kind === 'fleet-canvas') return 'Canvas';
  if (kind === 'orchestrator') return 'Orchestrator';
  if (kind === 'chat') return 'Agent';
  return 'Assistant';
}

export function laneDisplayTitle(
  packet?: Pick<WorkspaceOrchestrationPacketBadge, 'title'> | null,
  kind?: 'chat' | 'llm-chat' | 'terminal' | 'canvas' | 'orchestrator' | 'fleet-canvas',
) {
  const title = packet?.title?.trim();
  return title || adHocLaneTitle(kind);
}

/**
 * Canonical runtime → human label. The single source of truth for naming a
 * runtime in the UI ("Codex" / "Claude Code" / "Gemini" / "OpenCode 2"). Never
 * returns a raw id; an unknown/empty runtime yields the generic 'Agent'.
 */
export function runtimeDisplayLabel(runtime?: OrchestratorRuntime | string | null): string {
  const cap = runtime ? ORCHESTRATOR_RUNTIMES[runtime as OrchestratorRuntime] : null;
  return cap?.label ?? 'Agent';
}

/**
 * Canonical agent/session display label. **Never returns a raw id or prefix** —
 * the worst case is the runtime's human label ("Codex") or 'Agent'. Use this
 * everywhere a session/agent needs a name (tab titles, agent tiles, sub-agent
 * rows) so the fallback lives in ONE place and can't drift into id-slicing
 * (`sessionKey.split(':').pop()?.slice(0, 12)` on an owned key yields the
 * literal "codex-owned-", the recurring leak this prevents by construction).
 */
export function agentDisplayLabel(input: {
  name?: string | null;
  title?: string | null;
  sessionKey?: string | null;
  runtime?: OrchestratorRuntime | string | null;
}): string {
  const explicit = input.name?.trim() || input.title?.trim();
  if (explicit) return explicit;
  const runtime = input.runtime
    ?? (input.sessionKey ? resolveDisplayRuntime({ lane: { sessionKey: input.sessionKey } }) : null);
  return runtimeDisplayLabel(runtime);
}

function openClawAgentName(agent?: string | null): string {
  const normalized = agent?.trim();
  if (!normalized) return 'Mister';
  if (normalized === 'main' || normalized === 'main-public' || normalized === 'mister-scribe') return 'Mister';
  return normalized;
}

export function orchestratorBackendDisplayLabel(input: {
  backend?: OrchestratorBackendId | string | null;
  agent?: string | null;
}): string | null {
  switch (input.backend) {
    case 'hermes':
      return 'Hermes';
    case 'openclaw': {
      const agentId = input.agent?.trim() || 'main';
      return `OpenClaw · ${openClawAgentName(agentId)} · ${agentId}`;
    }
    case 'fable':
      return 'Fable';
    case 'collide':
      return 'Collide';
    case 'codex':
      return 'Codex';
    case 'claude':
      return 'Claude Code';
    case 'acp':
      return 'ACP';
    case 'o8':
      return 'o8';
    default:
      return null;
  }
}
