/**
 * Resolve the runtime to display for a packet by trusting the lane's
 * sessionKey prefix over `packet.runtime`. Older packets can have stale
 * `packet.runtime` values (e.g. 'codex' on a packet whose lane is actually
 * gemini-backed), so the sessionKey — which is generated by the runtime
 * adapter at session-launch time — is the authoritative source.
 *
 * Falls back to `packet.runtime` when the sessionKey is absent or its prefix
 * is unrecognized, and to `'codex'` only when both are missing.
 */
export function resolveDisplayRuntime(
  packet?: { runtime?: OrchestratorRuntime | string | null; lane?: { sessionKey?: string | null } | null } | null,
): OrchestratorRuntime {
  const sessionKey = packet?.lane?.sessionKey?.trim() ?? '';
  if (sessionKey) {
    const ownedRuntime = (Object.keys(ORCHESTRATOR_RUNTIMES) as OrchestratorRuntime[])
      .find((runtime) => sessionKey.startsWith(`${runtime}-owned:`));
    if (ownedRuntime) return ownedRuntime;
    if (sessionKey.startsWith('gemini-owned:') || sessionKey.startsWith('gemini:')) {
      return 'gemini';
    }
    if (sessionKey.startsWith('claude-code:') || sessionKey.startsWith('claude-code-')) {
      return 'claude-code';
    }
    if (sessionKey.startsWith('opencode-owned:') || sessionKey.startsWith('opencode:')) {
      return 'opencode';
    }
    if (
      sessionKey.startsWith('codex:')
      || sessionKey.startsWith('codex-owned:')
      || sessionKey.startsWith('codex-discovered:')
      || sessionKey.startsWith('codex-live:')
    ) {
      return 'codex';
    }
  }
  const runtime = packet?.runtime;
  if (runtime && ORCHESTRATOR_RUNTIMES[runtime as OrchestratorRuntime]) {
    return runtime as OrchestratorRuntime;
  }
  return 'codex';
}

export interface OrchestratorDisplayTone {
  label: string;
  shortLabel: string;
  color: string;
  background: string;
  border: string;
  dot: string;
}

/** Short-label abbreviations not stored in the capability map (display-only). */
const RUNTIME_SHORT_LABELS: Partial<Record<OrchestratorRuntime, string>> = {
  codex: 'CX',
  'claude-code': 'CC',
  gemini: 'GM',
  opencode: 'OC2',
};

export function orchestratorRuntimeTone(runtime?: OrchestratorRuntime | string | null): OrchestratorDisplayTone {
  const cap = runtime ? ORCHESTRATOR_RUNTIMES[runtime as OrchestratorRuntime] : null;
  if (cap) {
    const color = cap.accentColor;
    // Parse hex to rgba — hex is always 7-char #rrggbb from the map
    const r = parseInt(color.slice(1, 3), 16);
    const g = parseInt(color.slice(3, 5), 16);
    const b = parseInt(color.slice(5, 7), 16);
    return {
      label: cap.label,
      shortLabel: RUNTIME_SHORT_LABELS[runtime as OrchestratorRuntime] ?? cap.shortLabel,
      color,
      background: `rgba(${r}, ${g}, ${b}, 0.12)`,
      border: `rgba(${r}, ${g}, ${b}, 0.2)`,
      dot: color,
    };
  }

  // Unknown runtime — fall back to codex blue
  return {
    label: 'Codex',
    shortLabel: 'CX',
    color: '#2563eb',
    background: 'rgba(37, 99, 235, 0.12)',
    border: 'rgba(37, 99, 235, 0.2)',
    dot: '#2563eb',
  };
}

